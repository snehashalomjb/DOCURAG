# --- PDF GENERATOR UTILITY ---
class ChatPDF(FPDF):
    def header(self):
        self.set_font('helvetica', 'B', 15)
        self.set_text_color(99, 102, 241)  # Indigo #6366F1
        self.cell(0, 10, 'DOCURAG - Q&A Chat History Export', border=False, ln=True, align='L')
        self.set_draw_color(226, 232, 240)  # Light gray divider
        self.line(10, 20, 200, 20)
        self.ln(10)
         
    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f'Page {self.page_no()}/{{nb}} | Generated by DOCURAG', align='C')

def export_chat_to_pdf(messages: List[Dict[str, Any]]) -> bytes:
    pdf = ChatPDF()
    pdf.alias_nb_pages()
    pdf.add_page()
    
    for idx, msg in enumerate(messages):
        role = msg["role"]
        content = msg["content"]
        
        # Header block
        pdf.set_font('helvetica', 'B', 11)
        if role == "user":
            pdf.set_text_color(30, 41, 59)  # Slate 800
            pdf.cell(0, 8, f'User Question {idx//2 + 1}:', ln=True)
        else:
            pdf.set_text_color(99, 102, 241)  # Indigo
            pdf.cell(0, 8, f'Grounded Answer {idx//2 + 1}:', ln=True)
             
        # Content
        pdf.set_font('helvetica', '', 10)
        pdf.set_text_color(51, 65, 85)  # Slate 700
        clean_content = content.encode('latin-1', 'replace').decode('latin-1')
        pdf.multi_cell(0, 5, clean_content)
        
        # Sources block
        if role == "assistant" and msg.get("sources"):
            pdf.ln(2)
            pdf.set_font('helvetica', 'I', 9)
            pdf.set_text_color(100, 116, 139)  # Slate 500
            pdf.cell(0, 5, "Sources Used:", ln=True)
            
            for src_idx, src in enumerate(msg["sources"]):
                if isinstance(src, dict):
                    file_info = src.get('source_doc', 'Unknown Document')
                    chunk_text = src.get('chunk', '')[:120].strip() + "..."
                    confidence = src.get('confidence', 'Unknown')
                else:
                    file_info = "Document Reference"
                    chunk_text = str(src)[:120].strip() + "..."
                    confidence = "Unknown"
                
                clean_ref = f"  [{src_idx+1}] File: {file_info} | Confidence: {confidence} | Text: {chunk_text}"
                clean_ref_encoded = clean_ref.encode('latin-1', 'replace').decode('latin-1')
                pdf.multi_cell(0, 4, clean_ref_encoded)
         
        pdf.ln(8)
    return bytes(pdf.output())

# --- UTILITY TO ENSURE BACKEND IS RUNNING ---
def is_port_open(port: int) -> bool:
    """Check if a specific local port is active."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        return s.connect_ex(('127.0.0.1', port)) == 0

def start_backend_server():
    """Starts the FastAPI backend using uvicorn in a background process if not already running."""
    if not is_port_open(8000):
        with st.spinner("Initializing DOCURAG Core Backend Engine..."):
            python_bin = sys.executable
            logger_env = os.environ.copy()
            logger_env["PYTHONUNBUFFERED"] = "1"
            
            subprocess.Popen(
                [python_bin, "-m", "uvicorn", "app.backend.main:app", "--host", "127.0.0.1", "--port", "8000"],
                env=logger_env,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            
            # Poll /health endpoint
            max_retries = 30
            for i in range(max_retries):
                try:
                    res = requests.get(f"{BACKEND_URL}/health", timeout=1)
                    if res.status_code == 200:
                        break
                except requests.exceptions.RequestException:
                    pass
                time.sleep(0.5)
            else:
                st.error("Could not establish connection to backend server. Please refresh or run python run.py manually.")
                st.stop()

# Auto-start backend
start_backend_server()

