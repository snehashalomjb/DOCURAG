# Helper function to submit query
def execute_query(prompt_text: str):
    # 1. User Message
    st.session_state.messages.append({"role": "user", "content": prompt_text})
    
    # We make the API call
    history_payload = [
        {"role": msg["role"], "content": msg["content"]} 
        for msg in st.session_state.messages[:-1]
    ]
    
    payload = {
        "query": prompt_text,
        "session_id": st.session_state.session_id,
        "history": history_payload,
        "top_k": top_k,
        "gemini_api_key": st.session_state.api_key
    }
    
    try:
        res = requests.post(f"{BACKEND_URL}/query", json=payload)
        if res.status_code == 200:
            result = res.json()
            answer = result["answer"]
            sources = result["sources"]
            saved_sources = [dict(s) for s in sources]
            st.session_state.messages.append({
                "role": "assistant",
                "content": answer,
                "sources": saved_sources
            })
        else:
            st.error(f"Error querying assistant: {res.json().get('detail', 'Unknown error')}")
    except Exception as e:
        st.error(f"Could not connect to backend server: {str(e)}")

